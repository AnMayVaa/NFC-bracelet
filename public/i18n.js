const LANGS = [
  { code: 'en', label: 'English', locale: 'en' },
  { code: 'ko', label: '한국어', locale: 'ko' },
  { code: 'zh', label: '中文', locale: 'zh-Hans' },
  { code: 'ja', label: '日本語', locale: 'ja' },
  { code: 'th', label: 'ไทย', locale: 'th' }
];

let LANG = 'en';
try { const saved = localStorage.getItem('wb-lang'); if (I18N[saved]) LANG = saved; } catch (_) {}

function t(key, vars = {}) {
  const s = I18N[LANG]?.[key] ?? I18N.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

const locale = () => LANGS.find(l => l.code === LANG)?.locale || 'en';

function applyI18n(root = document) {
  document.documentElement.lang = locale();
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
}

function setLang(code) {
  if (!I18N[code]) return;
  LANG = code;
  try { localStorage.setItem('wb-lang', code); } catch (_) {}
  applyI18n();
}

// Theme: light by default, remembered per device
function currentTheme() {
  try { return localStorage.getItem('wb-theme') === 'dark' ? 'dark' : 'light'; } catch (_) { return 'light'; }
}
function setTheme(theme) {
  document.documentElement.dataset.theme = theme;
  try { localStorage.setItem('wb-theme', theme); } catch (_) {}
  document.querySelector('meta[name="theme-color"]')?.setAttribute('content', theme === 'dark' ? '#15181C' : '#7CC3E0');
}
document.documentElement.dataset.theme = currentTheme();
